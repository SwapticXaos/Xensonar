'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const lab=fs.readFileSync(path.join(root,'src/rooms/lab.js'),'utf8');
const viewPath=path.join(root,'src/rooms/00_empty_audio_p32.js');
assert(fs.existsSync(viewPath),'P32 real no-audio view component missing');
const view=fs.readFileSync(viewPath,'utf8');
assert(view.includes('function __XenForgeNoAudioP32('),'renderable component absent');
assert(view.includes('NO SIGNAL')&&view.includes('NO SOUND'),'both pseudo-audio masks required');
assert(view.includes('data-p32-import-mirror-triangle'),'red triangle anchor missing');
assert(view.includes('data-forge-rack-import-audio'),'existing Import Audio must be connector target');
assert(fs.readFileSync(path.join(root,'styles/areas/040_xen-p9-m9-cockpit-canonical.css'),'utf8').includes('prefers-reduced-motion'),'respect reduced animation settings');
assert(view.includes('pointerEvents:\'none\''),'connectors must not capture input');
assert(lab.includes(':u.jsx(__XenForgeNoAudioP32'),'no-signal UI must exist only in no-audio branch');
assert(!lab.includes('Load an audio source to create a generous view range above'),'old unhelpful placeholder should be replaced');
assert(view.includes('onImport')&&lab.includes('onImport:rt'),'no duplicate importer; use existing input click port');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'source-manifest.json')));
const files=manifest.sources.flatMap(s=>s.files);
assert(files.indexOf('src/rooms/00_empty_audio_p32.js')<files.indexOf('src/rooms/lab.js'));
console.log('P32 PASS: no-audio-only pseudo-wave masks, mirrored triangle, three-corner animation, original importer retained');
