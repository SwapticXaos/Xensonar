'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const donor=read('src/rooms/00_idle_wave_donor_p33.js');
const view=read('src/rooms/00_empty_audio_p32.js');
assert(donor.includes('drawIdle(')&&donor.includes('buildTextMask(')&&donor.includes('IDLE_CYCLE'));
assert(donor.includes('xen-waveform-donor-idle-render'), 'provenance marker missing');
assert(!donor.includes('AudioContext')&&!donor.includes('decodeFile'), 'no second audio engine');
assert(view.includes('__XenIdleWaveDonorP33'), 'must reuse extracted donor renderer');
assert(view.includes('NO SIGNAL')&&view.includes('NO SOUND'));
assert(view.includes('data-p33-animated-canvas'), 'original P32 static placeholder must be replaced by donor canvas');
assert(view.includes('data-p33-seven-bars')&&view.includes('Seven Bars'), 'seven dummy bars');
assert(view.includes('data-p33-inactive-rack'), 'full faded export rack should be visible before audio');
assert(view.includes('inert:true') && view.includes('},controls);'), 'same real controls must be inert in first-contact state');
assert(!view.includes('const waveBars='),'static pseudo-waveform should no longer render');
const manifest=JSON.parse(read('source-manifest.json'));
const files=manifest.sources.flatMap(s=>s.files);
assert(files.indexOf('src/rooms/00_idle_wave_donor_p33.js')<files.indexOf('src/rooms/00_empty_audio_p32.js'));
console.log('P33 source PASS: extracted donor renderer, seven dummy bars, inactive controls, original importer retained');
