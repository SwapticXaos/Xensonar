'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const code=fs.readFileSync(path.join(root,'src/rooms/lab.js'),'utf8');
const presenter=fs.readFileSync(path.join(root,'src/rooms/00_forge_rack_presentation.js'),'utf8');
const paint=fs.readFileSync(path.join(root,'src/forge/editor/02_tools_and_audio_inputs.js'),'utf8');
const style=fs.readFileSync(path.join(root,'styles/areas/040_xen-p9-m9-cockpit-canonical.css'),'utf8');
const start=code.indexOf("u.jsx(__ForgeRackRows,{primary:__ForgeRackOrder('primary',{");
const end=code.indexOf('className:"xen-forge-name-section',start);
const rack=code.slice(start,end);
assert(start!==-1&&end>start);
for(const x of ['xen-forge-action-row-primary','xen-forge-action-row-secondary'])assert(presenter.includes(x),'Missing shared layout '+x);
for(const x of ['extract','pink','root','material','donor','sample'])assert(rack.includes("__ForgeRackClass('"+x+"'")&&presenter.includes('xen-forge-tile-'+x),'Missing shared live style '+x);
const expectedPrimary=['__ForgeRackCaption("load")','__ForgeRackCaption("repair"','__ForgeRackCaption("apply")','__ForgeRackCaption("extract")','xen-forge-giant-play','__ForgeRackCaption("material")'];
const primaryStart=rack.indexOf("primary:__ForgeRackOrder('primary',{"),secondaryStart=rack.indexOf("secondary:__ForgeRackOrder('secondary',{");
assert(primaryStart>=0&&secondaryStart>primaryStart);
const primary=rack.slice(primaryStart,secondaryStart),secondary=rack.slice(secondaryStart);
for(const x of expectedPrimary)assert(primary.includes(x),'Primary action missing: '+x);
for(const x of ['__ForgeRackCaption("pink")','__ForgeRackCaption("root")','__ForgeRackCaption("sample")','__ForgeRackCaption("donor")','u.jsx(__AudioToCarrierControls'])assert(secondary.includes(x),'Secondary action missing: '+x);
assert(!primary.includes('__ForgeRackCaption("pink")'),'Pink track must not be on first row');
const toolList=paint.slice(paint.indexOf('const a4e='),paint.indexOf(';',paint.indexOf('const a4e=')));
assert(!toolList.includes('id:"threshold"'),'Threshold door must not appear in painting tool menu');
assert(!toolList.includes('id:"sourceTrace"'),'DNA trace must not appear in painting tool menu');
assert(code.includes('case"threshold":c.applyThresholdBrush('),'Existing threshold internal behavior accidentally deleted');
assert(code.includes('case"sourceTrace":{const f=e.sourceAsset?.analysisCache;'),'Existing trace internal behavior accidentally deleted');
assert(/\.xen-forge-action-row\s*\{[^}]*flex-wrap\s*:\s*nowrap/m.test(style),'No accidental wrapping into cross-breaking rows');
assert(/\.xen-forge-tile-extract\s*\{[^}]*width\s*:\s*248px/m.test(style),'Extract Timbre must restore original 248px width');
assert(/\.xen-forge-tile-pink\s*\{[^}]*width\s*:\s*271px/m.test(style),'Pink Track must restore original 271px width');
assert(/\.xen-forge-tile-material\s*\{[^}]*width\s*:\s*3(?:0|1)\dpx/m.test(style),'Outer Material Track may be slightly shorter');
assert(/\.xen-carrier-transform\s*\{[^}]*min-width\s*:\s*13\.5rem/m.test(style),'Carrier may grow with test tube');
console.log('CROSS RACK RED/GREEN PASS: fixed two-row semantic order, restored widths, retired tools only from menu');
