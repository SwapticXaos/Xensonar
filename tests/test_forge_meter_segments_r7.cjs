'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const lab = fs.readFileSync(path.join(root, 'src/rooms/lab.js'), 'utf8');
const css = fs.readFileSync(path.join(root,'styles/areas/040_xen-p9-m9-cockpit-canonical.css'), 'utf8');
const start = lab.indexOf('function __ForgeMaterialQuickFields(');
const end = lab.indexOf('function __ForgeMaterialMetadata(', start);
assert.ok(start > 0 && end > start);
const fields=lab.slice(start,end);
const labels=['Number of Bars','Number of Segments','Frequency Anchor (Hz)'];
for(const label of labels) assert.ok(fields.includes(`field('${label}'`), `Missing independent quick field ${label}`);
assert.ok(labels.every((label,i)=>i===0||fields.indexOf(`field('${labels[i-1]}'`)<fields.indexOf(`field('${label}'`)),'Expected Bars → Segments → Anchor');
assert.match(fields,/guideSegments/, 'Independent segment state required');
assert.match(fields,/onPatch\(\{guideSegments:/, 'Segment edits must preserve authoritative guideSegments state');
assert.doesNotMatch(fields,/bars\s*\/\s*4|guideSegments:\s*[^,]*bars\s*\//,'No inferred 4/4 subdivision');
assert.match(css,/\.xen-forge-inline-metadata\s*\{[^}]*grid-template-columns:[^}]*\s+[^}]*\s+[^}]*;/s,'Use three columns without a new row');
const meterStart=lab.indexOf('function wGe('), meterEnd=lab.indexOf('function hA(', meterStart);
assert.ok(meterStart>=0&&meterEnd>meterStart);
const meter=lab.slice(meterStart,meterEnd);
assert.match(meter,/guideMarkers/, 'Taktometer must use the persisted marker array');
assert.match(meter,/guideSegments/, 'Taktometer must expose chosen subdivision, not an implicit four');
const materialState=fs.readFileSync(path.join(root,'src/app/forge/05_forge_state_and_analysis.js'),'utf8');
assert.match(materialState,/t\.guideSegments!==void 0\?cc\(t\.guideSegments\)/,'Existing state normalization for segments must stay');
assert.match(materialState,/a\?yu\(r\):e\.guideMarkers/,'Changing segment count recalculates marker positions');
console.log('PASS: bars, segments and frequency independently editable; metadata-backed guide markers drive Taktometer; compact three-column UI');
