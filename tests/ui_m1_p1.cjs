const cursorExpr = main.match(/const bassGridTuningHandle=([^;]+);t\.currentTarget\.style\.cursor=/)?.[1];
assert.ok(cursorExpr,'actual main-room cursor condition found');
const actualCursorCondition = Function('e','n','r','__XenBassGrid',`return (${cursorExpr});`);
const liveBassGrid = {visualRows:()=>[{freq:440,degree:7}]};
const activeMain = {nexusActive:true,gameWidth:640,yFromFreq:hz=>hz/4};
assert.equal(actualCursorCondition(activeMain,631,110,liveBassGrid),true,'Power ON right row signals tuning');
assert.equal(actualCursorCondition({...activeMain,nexusActive:false},631,110,liveBassGrid),false,'Power OFF right row has no tuning cursor');
assert.equal(actualCursorCondition(activeMain,580,110,liveBassGrid),false,'central painting field does not signal tuning');
assert.equal(actualCursorCondition(activeMain,631,150,liveBassGrid),false,'right empty space does not falsely signal tuning');
assert.equal(actualCursorCondition(activeMain,631,110,{visualRows:()=>[]}),false,'no tuning rows = no tuning cursor');
