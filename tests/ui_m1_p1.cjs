assert.match(lab,/data-forge-draw-play/,'interactive top play');
assert.match(lab,/__ForgeHeaderPlay/,'top has own carrier-play label');
assert.match(lab,/onClick:\(\)=>void __ForgeTransportAccess\.activate\(\)/,'top reuses the green carrier render-fill player, not Raw Audio');
