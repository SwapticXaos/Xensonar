'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const lab=read('src/rooms/lab.js');
const forge=read('src/forge/editor/09_workflow_controls.js');
const rack=read('src/factories/ForgeTransportRack.js');
const css=read('styles/areas/040_xen-p9-m9-cockpit-canonical.css');
const upperName=read('styles/areas/028_inline-028.css');
const smallFace=upperName.match(/\.f35-navigator-name-glyph,\.xen-forge-draw-play-word\{([^}]*)\}/)?.[1];
const name=upperName.match(/\.f35-navigator-name-glyph\{([^}]*)\}/)?.[1]?.replace(/\/\*[\s\S]*?\*\//g,'');
const playButton=css.match(/\.xen-forge-draw-play\{([^}]*)\}/)?.[1];
const playWord=css.match(/\.xen-forge-draw-play-word\{([^}]*)\}/)?.[1];
assert(smallFace&&name&&playButton&&playWord,'Both upper titles use ONE shared font source');
const prop=(rules,key)=>rules.match(new RegExp('(?:^|;)\\s*'+key+'\\s*:\\s*([^;]+)'))?.[1].trim();
for(const p of ['font-family','font-size','font-weight','line-height','letter-spacing']){
 assert(prop(smallFace,p),'Shared title metric '+p+' must exist');
 assert(!prop(playWord,p),'PLAY must not re-declare '+p+' in another file');
}
assert.equal(prop(playWord,'transform'),prop(name,'transform'),'PLAY remains exactly condensed like NAME');
assert.equal(prop(smallFace,'font-size'),'34px!important');
assert.equal(prop(playWord,'transform'),'scaleX(.62)');
assert.ok(!/font-size/.test(playButton),'Upper PLAY button should not inherit giant font sizing');
assert.match(css,/\.xen-forge-draw-play:hover:not\(:disabled\)[^{]*\{[^}]*#ff6cda/,'PLAY hover must turn pink');
assert.match(lab, /u\.jsx\(__ForgeHeaderPlay,\s*\{\s*\}\)/,'Header replaces static Draw with its own small button component');
const helper=lab.match(/function __ForgeHeaderPlay\(\)\{([\s\S]*?)\n\}/)?.[1];
assert.ok(helper,'Header PLAY component must exist');
assert.match(helper,/__ForgeTransportAccess\.activate\(\)/,'Upper PLAY must call real Carrier transport');
assert.match(helper,/__ForgeTransportAccess\.subscribe/,'Header PLAY needs live transport availability');
assert.doesNotMatch(helper,/querySelector|xen-forge-giant-play|\.click\(/,'Cannot activate Raw Audio preview or synthetic DOM click');
assert.match(rack,/data-xensonar-spectralforge-render-fill-button/,'Existing green carrier player remains present');
assert.match(rack,/onClick:\(\)=>void __ForgeTransportAccess\.activate\(\)/,'Green carrier player uses same transport access');
const start=forge.indexOf('const __ForgeTransportAccess=(()=>{');
const end=forge.indexOf('})();',start);
assert(start>=0&&end>start,'Shared owner implementation present');
const ctx={};
vm.runInNewContext(forge.slice(start,end+5)+'\nthis.access=__ForgeTransportAccess;',ctx);
const api=ctx.access;
let carrier=0,stop=0;
const off=api.attach({activate:()=>++carrier,stop:()=>++stop});
const sourceStart=lab.indexOf('function __ForgeHeaderPlay(){');
const sourceEnd=lab.indexOf('function __ForgeMiniPlay(){',sourceStart);
assert(sourceStart>=0&&sourceEnd>sourceStart,'Header PLAY component is a distinct source function');
const harness={P:{useSyncExternalStore:(subscribe,snapshot)=>snapshot()},u:{jsx:(tag,props)=>({tag,props})},__ForgeTransportAccess:api};
vm.runInNewContext(lab.slice(sourceStart,sourceEnd),harness);
const rendered=harness.__ForgeHeaderPlay();
assert.equal(rendered.tag,'button');
assert.equal(rendered.props.disabled,false,'Header PLAY enabled while green player mounted');
assert.equal(rendered.props.children.props.children,'PLAY','Small button owns PLAY ink itself');
rendered.props.onClick();
api.activate();
assert.equal(carrier,2,'Shared owner invokes the active carrier transport');
assert.equal(stop,0,'Never directly invokes raw audio preview');
off();assert.equal(api.snapshot().available,false,'Owner must detach on room exit');
assert.equal(harness.__ForgeHeaderPlay().props.disabled,true,'Header disables when transport absent');
api.activate();assert.equal(carrier,2,'No stale owner after room exit');
console.log('PASS M1 UI P2: Upper Play equals small Name optically, carrier green render-fill transport functionally');
