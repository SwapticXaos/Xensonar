'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const code=fs.readFileSync(path.resolve(__dirname,'../../../src/quickrack/equalizer/eq-core.js'),'utf8');
let cos=0,sin=0;
const instrumentedMath=Object.create(Math);
instrumentedMath.cos=(x)=>{cos++;return Math.cos(x)};
instrumentedMath.sin=(x)=>{sin++;return Math.sin(x)};
const s={localStorage:{getItem:()=>null,setItem(){}},window:{addEventListener(){}},requestAnimationFrame:()=>1,console,Math:instrumentedMath,Number,Array,Object,JSON,Set,WeakMap,WeakSet,Map,Date,setTimeout,clearTimeout};
vm.runInNewContext(code+'\nglobalThis.eq=__XenEQ;',s);
const eq=s.eq;
const cfg=eq.clean({...eq.neutral(),mode:'raster',bands:12,a:Array(360).fill(0)});
const p=eq.plan(cfg,48000),r1=eq.response(cfg,48000,240,p);
const used1=cos+sin;
const r2=eq.response(cfg,48000,240,p);
const used2=cos+sin-used1;
assert.deepEqual([...r2],[...r1]);
assert.ok(used1>=900,'first rendering should generate frequency-response geometry');
assert.equal(used2,0,'repeat rendering with identical rate and length must reuse geometry without further trigonometry');
const other=eq.response(cfg,44100,240,eq.plan(cfg,44100));
assert.equal(other.length,240);
assert.ok(cos+sin>used1,'different samplerate uses distinct geometry');
console.log('PASS P1.3 frequency-response geometry reuse; first trig',used1,'same geometry second',used2);
