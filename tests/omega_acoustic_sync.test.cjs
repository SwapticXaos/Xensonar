'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const base=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(base,'src/audio/03_acoustic_sync.js'),'utf8');
const recording=fs.readFileSync(path.join(base,'src/audio/03_recorder.js'),'utf8');
const encoder=fs.readFileSync(path.join(base,'src/audio/03_flac_encoder.js'),'utf8');
const boot=fs.readFileSync(path.join(base,'src/audio/03_rfl_transport_legacy.js'),'utf8');
const diagnose=fs.readFileSync(path.join(base,'src/runtime/instrument/05_timing_and_admission.js'),'utf8');
assert(source.length>100,'Require actual acoustic-sync implementation');
const context={Float32Array,Math,Number,Date,Array,Map,Set,Object,Int32Array,globalThis:null,performance:{now:()=>10100},setTimeout:()=>0,clearTimeout(){}};
context.globalThis=context;
vm.createContext(context);vm.runInContext(source+'\nthis.plan=f319AcousticPlan;this.stamp=f319AcousticStampBlock;this.sync=__XenAcousticSync;',context);
const makeBuffer=(length=48000,rate=48000)=>({sampleRate:rate,length,duration:length/rate});
const markers=[{id:'marker-1',timeMs:300},{id:'marker-2',timeMs:750}];
const plan=context.plan(makeBuffer(),null,markers);
assert.equal(plan.stamps.length,2);
assert.equal(plan.stamps[0].sampleIndex,14400);
assert.equal(plan.stamps[1].sampleIndex,36000);
const left=new Float32Array(4096),right=new Float32Array(4096);
const originalLeft=new Float32Array(left),originalRight=new Float32Array(right);
context.stamp(left,right,12288,plan.stamps);
assert(left.some(x=>x!==0),'Must embed actual correlated PCM signal');
assert(right.some(x=>x!==0),'Both channels must carry recognizable signal');
let changed=0;for(let i=0;i<left.length;i++){if(left[i]!==0){changed++;assert(Math.abs(left[i]+right[i])<1e-7,'Polarity antisymmetry');}}
assert(changed>300,'Spread code across multiple bursts, not a single click');
assert.deepEqual(Array.from(originalLeft),Array.from(new Float32Array(4096)),'source PCM must remain untouched');
assert.deepEqual(Array.from(originalRight),Array.from(new Float32Array(4096)));
const crop=context.plan(makeBuffer(),{startMs:400,endMs:900},markers);
assert.equal(crop.stamps.length,1);assert.equal(crop.stamps[0].id,'marker-2');assert.equal(crop.stamps[0].sampleIndex,16800);
const tooShort=context.plan(makeBuffer(600),null,[{id:'tiny',timeMs:0}]);
assert.equal(tooShort.stamps.length,0,'Do not output truncated patterns');
const x=context.sync;
x.begin({startedPerfMs:1000,sourceMode:'with_drums'});
const first=x.record({id:'marker-1',timeMs:300,perfMs:1300},'f9');
assert(first&&first.recordingId,'recording ID is stable');
assert.equal(x.read().markers.length,1);
x.exported({filename:'demo.flac',plan,format:'flac'});
const payload=x.read();assert.equal(payload.exports[0].filename,'demo.flac');
assert.equal(payload.exports[0].stamps[0].sampleIndex,14400);
assert.equal(payload.markers[0].recordingId,first.recordingId);
assert(recording.includes('f319AcousticPlan(')&&recording.includes('f319RecorderFlacEncode(recorded,range,'),'recorder must pass plan to encoder');
assert(encoder.includes('f319AcousticStampBlock('),'FLAC-worker PCM chunk must receive injected code');
assert(boot.includes('__XenAcousticSync.begin('),'record start must establish ID and clock');
assert(diagnose.includes('acoustic_sync_markers.json'),'runtime ZIP must carry sync metadata');
assert(diagnose.includes('__XenRecorderSyncMark'),'F8/runtime green marker must reach audio take');
console.log('Ω1-G Acoustic Sync PASS: marker plan, crop, PCM code, recording lifetime, diagnostic wiring');
