'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = process.argv[2] || process.cwd();
const read = (x) => fs.readFileSync(path.join(root,x), 'utf8');
const mf = JSON.parse(read('source-manifest.json'));
const names = new Set(mf.sources.flatMap(s => s.files));
for(const f of ['src/package_station/01_binary_archive.js','src/package_station/02_export_selection.js','styles/package_station/selection.css','src/contracts/16_workspace_export_stream.js','src/forge/stamps/01_atlas_2026_bridge.js','src/forge/stamps/02_atlas_audition.js','src/rooms/00_forge_rack_presentation.js','src/rooms/00_idle_wave_donor_p33.js','src/rooms/00_empty_audio_p32.js']) assert.ok(names.has(f),`merged manifest missing ${f}`);
assert.match(read('src/runtime/instrument/05_timing_and_admission.js'),/__xenPackageStation4\(\)/);
assert.match(read('src/app/forge/03_spectral_grid_and_archives.js'),/function __xenCaptureWorkspace4\(selection\)/);
assert.match(read('src/rooms/lab.js'),/__ForgeRackOrder\('primary'/);
assert.match(read('src/rooms/lab.js'),/__ForgeRackCaption\("extract"/);
assert.match(read('src/forge/stamps/02_atlas_audition.js'),/\w/);
assert.match(read('src/audio/03_pcm_master_recorder.js'),/function __xenMasterPcmWorkletModule\(/);
assert.match(read('src/audio/03_rfl_transport_legacy.js'),/await __xenCreateMasterPCMRecorder\(R,I\.stream,I\.__xenPcmTap\)/);
assert.match(read('src/audio/03_rfl_transport_legacy.js'),/Browser-Codec \(möglicherweise verlustbehaftet\)/);
const all = mf.sources.flatMap(s=>s.files);
assert.equal(all.length,new Set(all).size, 'module included twice');
assert.ok(all.indexOf('src/rooms/00_forge_rack_presentation.js') < all.indexOf('src/rooms/lab.js'));
assert.ok(all.indexOf('src/forge/stamps/02_atlas_audition.js') < all.indexOf('src/forge_and_melodic/10_audition_and_persistence.js'));
console.log('PASS: P4.1 and P37 RC4 and PCM2 merge capabilities, manifest order, single-owner source contracts');
