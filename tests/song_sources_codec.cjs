'use strict';
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const text=fs.readFileSync(path.join(root,'src/mix/03_meta_menu__before_v2-session-store.js'),'utf8');
const start=text.indexOf('const __XenMainRoomSessionBridge='),end=text.indexOf('})();',start)+5;
const box={__XenStarterInstalled:false,__xenRestoredWorkspace4:{},console};
vm.runInNewContext(text.slice(start,end)+';globalThis.bridge=__XenMainRoomSessionBridge',box);
let patches=[];
const params={waveOvertones:{Root:1,'3/2':.4},nexusVolumeOvertones:{Root:.2},keyboardHoldPatternSteps:[1,0,0],waveStarterHoldSegments:24};
box.bridge.attach({getSongParams:()=>params,nParamsUI:params,updateNParams:v=>{patches.push(v);Object.assign(params,v)},waveSoundPreset:'vibrato_glass',waveSoundEnabled:true,waveSoundVolume:.3});
const capture=box.bridge.captureSongSources();
assert.equal(capture.waveStarter.waveOvertones['3/2'],.4);
assert.equal(capture.particle.nexusVolumeOvertones.Root,.2);
params.waveOvertones.Root=0;params.keyboardHoldPatternSteps=[0,1,0];
assert.equal(capture.waveStarter.waveOvertones.Root,1,'snapshot must detach numeric maps');
assert.equal(capture.keyboard.keyboardHoldPatternSteps.join(','),'1,0,0','snapshot must detach hold mask');
box.bridge.applySongSources(capture);
assert.equal(params.waveOvertones.Root,1);
assert.equal(params.keyboardHoldPatternSteps.join(','),'1,0,0');
assert.equal(patches.length,1,'one batched musical parameter restore');
const before=patches.length;box.bridge.applySongSources(capture);
assert.equal(patches.length,before,'identical restore must not retrigger parameter updates');
console.log('PASS detached overtone maps and hold masks, changed-state restore, no-op restore');
