#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = process.cwd();
const entry = path.join(root, 'src/features/xensonar/browserImplant/worklet/processor.ts');
const outfile = path.join(root, 'src/features/xensonar/browserImplant/generated/xensonar-c11-worklet.bundle.js');
const sourceTs = path.join(root, 'src/features/xensonar/browserImplant/generated/xensonarC11WorkletSource.ts');

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: 'browser',
  format: 'esm',
  target: ['es2020'],
  minify: true,
  legalComments: 'none',
  sourcemap: false,
  treeShaking: true,
});
const js = fs.readFileSync(outfile, 'utf8');
fs.writeFileSync(sourceTs, `/* generated by tools/browser-implant/build-worklet.mjs */\nexport const XENSONAR_C11_WORKLET_SOURCE=${JSON.stringify(js)};\n`);
console.log(`[browser-implant] worklet bundle ${js.length} bytes`);
