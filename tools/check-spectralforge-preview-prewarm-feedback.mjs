#!/usr/bin/env node
import fs from 'node:fs';
const read = (path) => fs.readFileSync(path, 'utf8');
const assert = (condition, message) => { if (!condition) { console.error(`[xensonar][spectralforge-preview-prewarm-feedback] FAIL: ${message}`); process.exit(1); } };
const mustContain = (text, needle, label) => assert(text.includes(needle), `${label} must contain ${needle}`);
const mustMatch = (text, regex, label) => assert(regex.test(text), `${label} must match ${regex}`);
const cache = read('src/features/l3lab/spectralForge/audio/spectralPreviewRenderCache.ts');
const engine = read('src/features/l3lab/spectralForge/audio/AudioEngine.ts');
const transport = read('src/features/l3lab/spectralForge/components/TransportBar.tsx');
const activity = read('src/features/l3lab/spectralForge/components/previewSession/useTransportPreviewActivityGate.ts');
const presentation = read('src/features/l3lab/spectralForge/components/transportBar/TransportBarPresentation.tsx');
const readyGate = read('src/features/l3lab/spectralForge/components/previewSession/spectralForgeTransportReadyGate.ts');
mustContain(cache, 'spectralForgePreviewRenderInflightCache', 'cache module');
mustContain(cache, 'prewarmSpectralForgePreviewBuffer', 'cache module');
mustMatch(cache, /const inflight = spectralForgePreviewRenderInflightCache\.get\(key\);[\s\S]*if \(inflight\) return \{ buffer: await inflight, cacheHit: true \};/, 'inflight render coalescing');
mustContain(engine, 'prewarmPreviewRender(', 'AudioEngine');
mustContain(engine, 'prewarmSpectralForgePreviewBuffer(', 'AudioEngine prewarm delegates to shared cache');
mustContain(transport, 'const renderVersion = useStore((s) => s.renderVersion);', 'TransportBar change trigger');
mustContain(transport, 'prewarmRendering', 'TransportBar prewarm UI state');
mustContain(transport, 'audioEngine.prewarmPreviewRender(', 'TransportBar schedules background prewarm');
mustContain(transport, 'runSerialAfterPaintPreviewRender', 'TransportBar serial after-paint runner');
mustContain(transport, 'renderVersion <= 0', 'TransportBar does not prewarm untouched initial blank canvas');
mustContain(activity, ': { coldIdleMs: 2000, firstDelayMs: 80, retryDelayMs: 80 };', 'spectral quiet-window timing');
mustContain(transport, 'setTransportPrewarmProgress(0.035);', 'prewarm feedback starts with actual serial run');
mustContain(transport, 'resolveSpectralForgeTransportPrewarmStatus({', 'status comes from prewarm truth resolver');
mustContain(readyGate, 'resolveSpectralForgeTransportPreviewTruth(input)', 'ready gate delegates to preview truth');
mustContain(presentation, 'data-xensonar-spectralforge-render-fill-layered="true"', 'layered play-button render fill');
mustContain(presentation, 'aria-busy={props.renderFillActive || props.donorHearingPhase === "rendering"}', 'real render busy state exposed on play button');
console.log('[xensonar][spectralforge-preview-prewarm-feedback] OK');
