"""Render measured spectral arrays with exact Hz/time axes and Carrier curves.
Requires Pillow. Input arrays are generated by f43_spectrum_images.cjs from WAV.
"""
from pathlib import Path
import json, math
from PIL import Image, ImageDraw

root = Path('examples/f43')
phrase = json.loads((root / 'phrase.json').read_text())
labels = {'reference': 'Neutraler Donor', 'near': 'Annaeherung', 'one': 'Verzweigung: eine Ebene', 'branch': 'Verzweigung: zwei Ebenen'}
for meta_path in sorted(root.glob('*_image.json')):
    stem = meta_path.name.removesuffix('_image.json')
    meta = json.loads(meta_path.read_text())
    source, label = stem.split('_', 1)
    width, height, left, top = 900, 360, 64, 36
    image = Image.new('RGB', (width+left+20, height+top+45), '#081719')
    measured = Image.frombytes('RGBA', (meta['width'], meta['height']), (root/(stem+'.rgba')).read_bytes())
    measured = measured.resize((width, height), Image.Resampling.BILINEAR)
    image.paste(measured, (left, top), measured)
    draw = ImageDraw.Draw(image)
    draw.text((left, 12), source + ' | ' + labels[label], fill='#d9f5ed')
    def row(hz): return top+height*(1-math.log(max(20,hz)/20)/math.log(1000))
    for hz in [20,50,100,200,500,1000,2000,5000,10000,20000]:
        y = round(row(hz))
        draw.line((left,y,left+width,y), fill='#24403f')
        draw.text((5,y-5), str(hz)+' Hz', fill='#95bcb7')
    duration = phrase['durationSec']
    for sec in range(math.floor(duration)+1):
        x=left+width*sec/duration
        draw.line((x,top,x,top+height), fill='#24403f')
        draw.text((x,top+height+12), str(sec)+' s', fill='#95bcb7')
    for event in phrase['events']:
        part=[]
        for i in range(241):
            u=i/240
            def curve(values, log=False):
                p=u*(len(values)-1); a=math.floor(p); b=min(a+1,len(values)-1); f=p-a
                return math.exp(math.log(values[a])*(1-f)+math.log(values[b])*f) if log else values[a]*(1-f)+values[b]*f
            if curve(event['gain']) <= 1e-5:
                if len(part)>1: draw.line(part, fill='#f0c39a', width=2)
                part=[]; continue
            time=event['startSec']+u*(event['endSec']-event['startSec'])
            part.append((left+width*time/duration,row(curve(event['pitch'],True))))
        if len(part)>1: draw.line(part,fill='#f0c39a',width=2)
    image.save(root/(stem+'.png'))
    (root/(stem+'.rgba')).unlink()
print('PASS measured comparison images with Carrier and exact axes')
