'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const source=fs.readFileSync('src/nodal/12_surface_runtime.js','utf8');
const make=new Function('__XenNodalLibrary','__XenNodalLive','__XenNodalModel',source+';return createNodalSurfaceRuntime');
const defer=()=>{let resolve,reject;const promise=new Promise((a,b)=>{resolve=a;reject=b});return {promise,resolve,reject}};
const A=Object.freeze({name:'A',articulation:{durationSec:.1},seed:1});
const B=Object.freeze({name:'B',articulation:{durationSec:.1},seed:2});
const C=Object.freeze({name:'C',articulation:{durationSec:.1},seed:3});
const instruments={A,B,C},id=x=>'nodal:'+x+'@1';
const ctx={state:'running',currentTime:1,sampleRate:48000};
const gate={B:null,C:null};const notes=[],pinned=new Map(),routes=[];
const player={snapshot:()=>({disposed:false}),isPrepared:()=>true,async prepare(i){const name=i.name;if(gate[name])await gate[name].promise;},pin(i){pinned.set(i,(pinned.get(i)||0)+1);},unpin(i){pinned.set(i,(pinned.get(i)||0)-1);},route(...x){routes.push(x);},noteOn(i,opts){notes.push(i.name);return {id:'v'+notes.length,noteOff(){}};},dispose(){}};
const create=make({}, {}, {});const bridge=create({library:{list:()=>Object.keys(instruments).map(x=>({id:x,revision:1,instrument:instruments[x]}))},live:{createPlayer:async()=>player},model:{compile:()=>({cost:1,silent:false})}});
bridge.configure({getContext:()=>ctx,ensureReady:async()=>ctx,getOutput:()=>({}),prepareRoute:()=>({main:{}})});
const flush=()=>new Promise(r=>setImmediate(r));
(async()=>{
 await bridge.select('wave',id('A'));
 gate.B=defer();const pendingB=bridge.select('wave',id('B'));await flush();
 assert(bridge.note('wave',id('B'),{frequency:220},ctx),'A must remain playable while B prepares');
 assert.equal(notes.at(-1),'A');
 assert.equal(bridge.selectionStatus('wave').active,id('A'));
 gate.C=defer();const pendingC=bridge.select('wave',id('C'));await flush();
 gate.C.resolve();await pendingC;
 gate.B.resolve();await pendingB;
 assert.equal(bridge.selectionStatus('wave').active,id('C'),'late B must not overwrite C');
 assert.equal(pinned.get(A),0);assert.equal(pinned.get(C),1);
 assert(bridge.note('wave',id('C'),{frequency:330},ctx));assert.equal(notes.at(-1),'C');
 gate.B=defer();const pendingBroken=bridge.select('wave',id('B'));await flush();gate.B.reject(new Error('prepare failed'));await pendingBroken;
 assert.equal(bridge.selectionStatus('wave').active,id('C'),'B failure must retain C');
 assert.equal(bridge.selectionStatus('wave').phase,'error');
 const oldStatus=bridge.selectionStatus('wave');
 await bridge.preview('wave',id('A'),{frequency:440},ctx);
 assert.equal(notes.at(-1),'A','preview explicit program');
 assert.equal(bridge.selectionStatus('wave').active,oldStatus.active,'preview must not select');
 assert.equal(pinned.get(C),1,'preview must not unpin active program');
 console.log('PASS P1 A/B/C stale completion, live continuity, failure, isolated Nodal preview and pinning');
})().catch(e=>{console.error(e);process.exitCode=1});
