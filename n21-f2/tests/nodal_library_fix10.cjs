'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {load}=require('./offline_runtime.cjs');
const root=path.resolve(__dirname,'..');
const model=load(root);
const test=model.run(`(()=>{
  const a={...nodalStarter('glass'),name:'Gleichklang'};
  const b={...a,nodes:a.nodes.map((n,i)=>i===0?{...n,x:.61}:n)};
  const first=__XenNodalLibrary.save(a);
  const second=__XenNodalLibrary.save(b);
  const original=__XenNodalModel.serialize(first.instrument);
  const before=nodalInstrumentMenu({tracks:[],notes:[],nodalInstruments:{}})[0].options;
  const renamed=__XenNodalLibrary.rename(first.id,first.revision,'Eigenname');
  const after=__XenNodalLibrary.list();
  const preset='nodal:'+first.id+'@'+first.revision;
  const composer={tracks:[{id:'bass',instrumentPreset:preset}], notes:[], nodalInstruments:{[preset]:first.instrument}};
  __XenNodalLibrary.remove(first.id,first.revision);
  const retained=nodalInstrumentMenu(composer)[0].options;
  const deleted=nodalInstrumentMenu({tracks:[],notes:[],nodalInstruments:{[preset]:first.instrument}})[0].options;
  return {distinct:before[0].label!==before[1].label,containsOpaqueCodes:/nodal-[a-z0-9]+-[a-z0-9]+/.test(before[0].label), renamedName:renamed.instrument.name,revision:renamed.revision,count:after.length,original:JSON.parse(original).name, storedName:after.find(x=>x.id===first.id).instrument.name, retained:retained.some(x=>x.id===preset),deletedAbsent:!deleted.some(x=>x.id===preset),deleteLeavesLibraryCount:__XenNodalLibrary.list().length};
})()`);
assert(test.distinct,'Identical names must be distinguishable in dropdown');
assert.equal(test.containsOpaqueCodes,false,'Avoid exposing opaque technical IDs');
assert.equal(test.renamedName,'Eigenname');
assert.equal(test.revision,1,'Renaming cannot produce a new sound revision');
assert.equal(test.count,2,'Renaming cannot create a library duplicate');
assert.equal(test.original,'Gleichklang','Existing snapshot remains independent');
assert.equal(test.storedName,'Eigenname');
assert(test.retained,'Existing composition keeps deleted library sound');
assert(test.deletedAbsent,'Orphaned embedded copies not visible as live menu entries');
assert.equal(test.deleteLeavesLibraryCount,1);
const melodic=fs.readFileSync(path.join(root,'src/forge_and_melodic/06_note_editor_and_material_tools.js'),'utf8');
const bridge=require('./nodal_sources.cjs').readNodalSources(root);
assert(melodic.includes('NodalLibraryManager'),'The manager must appear next to the Melodic instrument selection');
assert(bridge.includes('function NodalLibraryManager('));
console.log('PASS: library identity, duplicate display names, rename, deletion and Melodic management');
