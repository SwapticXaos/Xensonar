'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const melodic = fs.readFileSync(path.join(root,'src/forge_and_melodic/06_note_editor_and_material_tools.js'),'utf8');
const css = fs.readFileSync(path.join(root,'styles/20_nodal_sound_designer.css'),'utf8');
const bridge = require('./nodal_sources.cjs').readNodalSources(root);
const componentStart = melodic.indexOf('function mQe(');
const componentEnd = melodic.indexOf('function ',componentStart+9);
const section = melodic.slice(componentStart,componentEnd < 0 ? undefined : componentEnd);
const marker = 'u.jsx(NodalLibraryManager,{composer:d,onMutateLoopComposer:p})';
assert.equal(section.split(marker).length - 1,1,'Only one library toggle should exist');
const grid = 'u.jsxs("div",{className:"grid gap-3 md:grid-cols-8"';
const gridStart = section.indexOf(grid);
const managerPos = section.indexOf(marker);
assert(gridStart >= 0 && managerPos > gridStart,'Library toggle must be an 8th child of the existing settings/instruments grid, not its own row above it');
const instrument4Pos = section.indexOf('dQe.map(',gridStart);
assert(managerPos > instrument4Pos,'Library toggle should follow the four instrument selectors in the same grid');
assert.match(css,/\.nd-library-manager\{[^}]*margin:0[^}]*border:0/,'Collapsed control must not add a boxed row');
assert.match(css,/\.nd-library-manager-content\{[^}]*position:absolute/,'Expanded manager should overlay instead of displacing the editing workspace');
assert(bridge.includes('nodalLibraryEntryLabel'), 'Existing library management must stay intact');
console.log('PASS FIX11: library toggle uses free grid cell and flyout does not consume layout height');
