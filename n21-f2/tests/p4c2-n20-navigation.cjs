assert.match(css,/width:78px;height:77px/,'tiles have same dimensions as existing violin tile');
assert.match(css,/background:#152e60/,'tiles use same background as existing violin tile');
assert.match(css,/@media\(min-width:1200px\)/,'responsive desktop grid');
assert.match(css,/\.n20-drum-pattern-and-reset/,'drum reset grouped with pattern dropdown');
assert.ok(manifest.styles.some(x=>x.file==='styles/25_n20_forge_navigation.css'),'new css included in standalone build');
console.log('PASS N20 layout, controls, events, persistence and manifest contracts');
