assert.match(melodic,/__mlOpenDrumMachineEvent/,'drum tile calls existing owner event');
assert.match(drums,/className:"n20-forge-nav-tile n20-forge-to-melodic"/,'melodic navigation tile is placed in drum header');
assert.match(drums,/xensonar:nodal-open-melodic/,'melodic tile calls existing owner event');
