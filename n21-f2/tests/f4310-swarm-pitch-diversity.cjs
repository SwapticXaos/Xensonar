'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const dir=path.join(__dirname,'../src');
const read=file=>fs.readFileSync(path.join(dir,file),'utf8');
const engine=read('runtime/instrument/01_voice_gradients_and_effects.js');
const start=engine.indexOf('MZ={'),end=engine.indexOf(',EZ=e=>',start);
assert.ok(start>=0&&end>start);const context={Math};vm.createContext(context);
vm.runInContext('const '+engine.slice(start,end)+';this.pitchEntropy=IZ;',context);
const fn=context.pitchEntropy;
const micro31=[440,440*2**(1/31)];
assert.equal(fn(micro31),0,'legacy chromatic rounds 31-EDO neighbors together');
assert.ok(fn(micro31,'microtonal')>0.98,'microtonal opt-in distinguishes 31edo neighbors');
assert.equal(fn([440,440],'microtonal'),0,'unison stays identical');
assert.equal(fn([440,880],'microtonal'),0,'octaves are equivalent');
assert.ok(fn([440,440*2**(5/1200)],'microtonal')>0,'five cents contribute smoothly');
assert.ok(fn([440,440*2**(5/1200)],'microtonal')<0.5,'five cents are less distinct than 31 edo');
assert.equal(fn([440,440*2**(100/1200)],'microtonal'),1,'wide intervals maximally distinct');
assert.ok(fn(Array(120).fill(440),'microtonal')===0,'bounded large swarm');
assert.ok(engine.includes('pitchEntropyMode:e.schwarmUi.pitchEntropyMode??"chromatic12"'),'live config transport');
assert.ok(read('runtime/instrument/02_observation_and_sample_storage.js').includes('U=IZ(x,n.pitchEntropyMode)'),'analysis consumes config');
assert.ok(/pitchEntropyMode:\s*"chromatic12",\s*updateMs:\s*120/.test(read('audio/03_rfl_transport_legacy.js')),'legacy default retained');
assert.ok(read('runtime/instrument/09_monitoring_and_manual_patterns.js').includes('children:"Microtonal"'),'UI opt-in available');
console.log('PASS F4.3.10 microtone-aware interval diversity, unchanged legacy, octave identity, bounded swarm, UI+runtime wiring');
