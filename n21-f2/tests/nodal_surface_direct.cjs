"use strict";
const assert=require('node:assert/strict'), fs=require('node:fs'), vm=require('node:vm'), path=require('node:path');
const src=path.join(__dirname,'../src/nodal/12_surface_runtime.js');
const code=fs.existsSync(src)?fs.readFileSync(src,'utf8'):'';
const ctx={currentTime:3,state:'running',audioWorklet:{},addEventListener(){},removeEventListener(){}};
const instrument=Object.freeze({schema:'xensonar-nodal-instrument',name:'Glass Organ',nodes:[{id:'one'}],referenceHz:220,articulation:{durationSec:.42}});
let entries=[{id:'my-tone',revision:2,instrument}];
const library={list:()=>entries};
let prepares=0,notes=[],render=0,acquires=0,disposed=0;
const player={async prepare(x){prepares++;assert(x && x.articulation && x.nodes);},noteOn(x,opts,t){notes.push({x,opts,t});return {id:'voice-'+notes.length}},dispose(){disposed++}};
const live={async createPlayer(c,d,a){assert.equal(c,ctx);assert.equal(d,'master');assert.equal(typeof a.acquire,'function');acquires++;return player}};
const model={compile:()=>({cost:2,silent:false,nodes:instrument.nodes})};
const sandbox={setTimeout,clearTimeout,Promise,console,performance,__XenNodalLibrary:library,__XenNodalLive:live,__XenNodalModel:model}; vm.createContext(sandbox);
assert(code.includes('function createNodalSurfaceRuntime'), 'Nodal surface factory must exist');
vm.runInContext(code,sandbox,{filename:src});
(async()=>{
 const bridge=sandbox.createNodalSurfaceRuntime({library,live,model});
 bridge.configure({getContext:()=>ctx,ensureReady:async()=>ctx,getOutput:()=> 'master',acquire:()=>({release(){}})});
 const options=bridge.options([{value:'dust_chime',label:'Dust Chime'}]);
 assert.equal(options.length,2); assert.equal(options[1].value,'nodal:my-tone@2');
 assert.equal(bridge.note('wave','nodal:my-tone@2',{frequency:440,gain:.5},ctx),null,'Never queue unprepared attacks');
 await bridge.select('wave','nodal:my-tone@2');
 const voice=bridge.note('wave','nodal:my-tone@2',{frequency:440,gain:.5,requestedAtMs:performance.now()},ctx);
 assert(voice);assert.equal(notes[0].opts.frequency,440);assert.equal(notes[0].x,instrument);
 assert.equal(render,0,'never render to PCM');
 assert.equal(bridge.note('wave','nodal:my-tone@2',{frequency:550,requestedAtMs:performance.now()-100},ctx),null,'stale attacks drop');
 assert.equal(bridge.note('wave','nodal:missing@1',{frequency:330},ctx),null,'unknown preset must not play fallback');
 await bridge.select('particle','nodal:my-tone@2');
 assert(bridge.note('particle','nodal:my-tone@2',{frequency:330,gain:.13},ctx));
 assert.equal(notes.length,2);
 // Library deletion or rename must invalidate the selected prepared recipe without a fallback.
 entries=[];
 assert.equal(await bridge.select('wave','nodal:my-tone@2'),null,'Deleted Nodal recipe must be invalidated on library refresh');
 assert.equal(bridge.note('wave','nodal:my-tone@2',{frequency:440},ctx),null,'Deleted recipe cannot continue sounding');
 const renamed=Object.freeze({...instrument,name:'New Glass Organ'});
 entries=[{id:'my-tone',revision:2,instrument:renamed}];
 assert(await bridge.select('wave','nodal:my-tone@2'),'Renamed immutable recipe must prepare again');
 assert(bridge.note('wave','nodal:my-tone@2',{frequency:440},ctx));
 assert.equal(notes.at(-1).x,renamed,'Renamed recipe must be the active sound');
 bridge.dispose();assert.equal(disposed,1,'Wave and particle share one player');
 console.log('PASS Nodal direct wave/particle, no PCM, prewarm, stale/drop, explicit id');
})().catch(e=>{console.error(e);process.exitCode=1});
