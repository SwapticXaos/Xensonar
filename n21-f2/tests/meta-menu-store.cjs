const quick={getItems:()=>[{kind:'bass',id:'clip:live',name:'Live Bass'}],replaceItems:arr=>{applied=arr.map(x=>({...x}));return arr},adapters:new Map(),icons:{grid:'🪜',material:'📀',rootFollow:'🎼',drum:'🥁',bass:'🎸'},subscribe:()=>()=>{},snapshot:()=>({items:[]})};
