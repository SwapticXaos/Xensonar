const m=ctx.testApi.store, entries=m.snapshot().items;
assert.equal(entries[0].id,'clip:live');
assert.equal(m.addItem({kind:'grid',id:'17edo',name:'17 EDO'}),true);
assert.equal(m.addItem({kind:'grid',id:'31edo',name:'31 EDO'}),true);
