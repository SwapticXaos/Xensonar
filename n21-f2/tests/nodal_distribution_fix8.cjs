'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=process.env.XEN_SOURCE_DIR||path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const ui=read('src/forge_and_melodic/07_tuning_and_logic_view.js');
const rfl=read('src/audio/01_voice_and_rfl_ownership.js');
const shell=read('src/app/forge/01_room_shell.js');
assert.ok(ui.includes('children:"Distribution · Melodic Loop"'),'User-approved Distribution label must be shown');
assert.ok(ui.includes('"aria-label":"Distribution composition name"'),'Editable name belongs on main panel');
assert.equal((ui.match(/children:"Material Name"/g)||[]).length,0,'Do not retain a duplicate hidden name editor');
assert.ok(ui.includes('value:e,onChange:w=>c(w.target.value),maxLength:160'),'The displayed name must be the existing materialName state');
assert.ok(ui.includes('onClick:()=>{le(je.id);void ue(je.id,je.instrumentPreset)}'),'Clicking instrument card selects and auditions its exact preset');
assert.ok(ui.includes('nodalFindInstrument(je.instrumentPreset,e)?.name'),'Nodal instrument labels must resolve snapshot names instead of exposing raw IDs');
assert.ok(rfl.includes('ensurePreviewAudioReady:__ensurePreviewAudioReady'),'Preview owns a distinct audio initialization route');
assert.ok(rfl.includes('Promise.resolve(__ensurePreviewAudioReady())'),'Gesture calls audio initialization synchronously');
assert.ok(!rfl.includes('drumPattern:"four_on_floor"'),'Preview must not invent a drum beat');
assert.ok(shell.includes('nexusActive:Gr||Pl,rootFollowLoopActive:et.rootFollowLoopActive'),'Preview opens RFL scheduler independently of Power');
assert.ok(shell.includes('__rflPreviewEnsureRef.current=Bs'),'Preview delegates audio ownership to the existing main AudioContext');
console.log('PASS: Distribution visible naming, true instrument audition, beat-free Power-independent RFL Preview');
