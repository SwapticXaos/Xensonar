const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const src = fs.readFileSync('src/myzel/01_effect_mapping.js', 'utf8');
const {myzelRandomEffectAssignments, myzelAssignEffectToNode, MYZEL_JI_EFFECTS} =
  vm.runInNewContext(src + '\n({myzelRandomEffectAssignments,myzelAssignEffectToNode,MYZEL_JI_EFFECTS})');
const seeded = seed => () => { seed = (1664525 * seed + 1013904223) >>> 0; return seed / 4294967296; };
const original = Array.from({length:12}, (_, i) => ({residentId:`node-${i}`,label:i?'9/8':'Root',ratio:i+1,originalValue:'untouched',isCustomResident:false}));
const first = myzelRandomEffectAssignments(original, seeded(42));
const replay = myzelRandomEffectAssignments(original, seeded(42));
const different = myzelRandomEffectAssignments(original, seeded(43));
assert.deepEqual(first.map(n=>n.myzelEffectModuleType), replay.map(n=>n.myzelEffectModuleType));
assert.notDeepEqual(first.map(n=>n.myzelEffectModuleType), different.map(n=>n.myzelEffectModuleType));
assert.equal(first.length, 12);
assert.equal(new Set(first.map(n=>n.myzelEffectModuleType)).size, 11);
assert.equal(new Set(MYZEL_JI_EFFECTS).size, 11);
assert.equal(first.filter(n=>n.myzelEffectModuleType===first[0].myzelEffectModuleType).length <= 2, true);
assert.equal(first.every((n,i)=>n.ratio===original[i].ratio && n.originalValue==='untouched'),true);
assert.equal(original.some(n=>n.myzelEffectModuleType), false);
const withCustom = [...original,{residentId:'extra-custom',isCustomResident:true,myzelEffectModuleType:'resonator'}];
const assignedCustom = myzelRandomEffectAssignments(withCustom, seeded(42));
assert.equal(assignedCustom[12].myzelEffectModuleType,'resonator');
const edited = assignedCustom.map(x=>({...x}));
assert.equal(myzelAssignEffectToNode(edited,'node-0','drive'),true);
assert.equal(edited[0].myzelEffectModuleType,'drive');
assert.equal(myzelAssignEffectToNode(edited,'extra-custom','drive'),false);
assert.equal(myzelAssignEffectToNode(edited,'node-1','made-up'),false);
assert.equal(myzelAssignEffectToNode(edited,'not-here','drive'),false);
const replaced = edited.map(x=>({...x,myzelEffectPresetId:'glas'}));
assert.equal(myzelAssignEffectToNode(replaced,'node-0','chorus'),true);
assert.equal('myzelEffectPresetId' in replaced[0],false);
console.log('PASS Myzel G2: seeded random JI/effect mapping, 11-organ coverage, manual override, custom protected');
