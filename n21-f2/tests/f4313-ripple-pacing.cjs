'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const css=fs.readFileSync('styles/22_emilia3.css','utf8');
const main=fs.readFileSync('src/runtime/01_instrument_state.js','utf8');
const h=main.match(/\bUJ=(\d+),ny=([\d.]+),Oy=/);
const bounds=main.match(/\bvr=(\d+),ir=(\d+),kx=/);
assert(h&&bounds,'mainroom reference parameters readable');
const [,radius,frameSpeed]=h.map(Number),fieldHeight=Number(bounds[2]);
const expectedDiameter=radius/fieldHeight*200;
const expectedTime=radius/(frameSpeed*60);
const diameter=Number(css.match(/\.emilia-b-ripple-wave\{[^}]*width:([\d.]+)%/)[1]);
const time=Number(css.match(/animation:emilia-b-ripple-flow\s+([\d.]+)s/)[1]);
assert(Math.abs(expectedDiameter-diameter)<.001,'ripple radius is mainroom-normalized to short field dimension');
assert(Math.abs(expectedTime-time)<.001,'mainroom wave pacing expressed as CSS duration');
assert.match(css,/animation:emilia-b-ripple-flow\s+[\d.]+s linear both/,'constant expansion speed; no shockwave acceleration');
assert.match(css,/@keyframes emilia-b-ripple-flow\{0%\{[^}]*scale\(\.02\)/);
assert.match(css,/100%\{[^}]*scale\(1\)/);
assert.match(css,/aspect-ratio:1\/1/,'circle stays circular at responsive field sizes');
const lab=fs.readFileSync('src/forge/emilia/02_lab_ui.js','utf8');
assert.match(lab,/afterAudioRelease\(d.next.x,d.next.y\)/,'release continues to await audio settle');
assert.match(lab,/className='emilia-b-ripple-wave'/,'separate compositor layer retained');
console.log('PASS F4.3.13: Haupt­raum-relative ring radius/speed/easing + composited wave unchanged');
