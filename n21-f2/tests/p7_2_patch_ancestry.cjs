'use strict';
// Independent, read-only witness: replay every declared source span in memory
// from the user's original Codex basis and compare to the patched checkout.
// Unlike hash-whitelisting, this fails on any additional or altered byte.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const patched=path.resolve(process.argv[2]||'.');
const original=process.argv[3]&&path.resolve(process.argv[3]);
const patchDir=process.argv[4]&&path.resolve(process.argv[4]);
assert(original&&patchDir,'Usage: node tests/p7_2_patch_ancestry.cjs <patched-root> <original-root> <handoff-patches>');
const sha=v=>crypto.createHash('sha256').update(v).digest('hex');
const read=(root,file)=>fs.readFileSync(path.join(root,file),'utf8');
const stages=fs.readdirSync(patchDir).filter(x=>/^0[0-8]_.*\.xpatch\.json$/.test(x)).sort();
assert.equal(stages.length,9,'Exactly nine functional stages must be represented');
const simulated=new Map();let edits=0,files=0;
for(const filename of stages){
 const patch=JSON.parse(fs.readFileSync(path.join(patchDir,filename)));
 for(const f of patch.files){
  const previous=simulated.has(f.path)?simulated.get(f.path):f.new_file?'':read(original,f.path);
  assert.equal(sha(previous),f.before_sha256||sha(''),`Unexpected predecessor of ${filename}: ${f.path}`);
  // xpatch offsets were generated by Python and index Unicode code points,
  // NOT JavaScript UTF-16 units (astral emoji must remain position-safe).
  let points=Array.from(previous);
  for(const edit of [...f.edits].reverse()){
   assert(edit.at>=0&&edit.at+edit.delete<=points.length,'Invalid patch span');
   points.splice(edit.at,edit.delete,...Array.from(edit.insert));
   edits++;
  }
  const result=points.join('');
  assert.equal(sha(result),f.after_sha256,`Unexpected output of ${filename}: ${f.path}`);
  simulated.set(f.path,result);files++;
 }
}
for(const [file,result] of simulated){
 assert.equal(read(patched,file),result,`Unauthorized source difference: ${file}`);
}
const manifestOld=JSON.parse(read(original,'source-manifest.json'));
const manifestNew=JSON.parse(read(patched,'source-manifest.json'));
assert.deepEqual(manifestNew.files.slice(1),manifestOld.files,'Existing source order must not change');
assert.equal(manifestNew.files[0],'src/handoff/00_chat_feature_addons.js','Expected explicit one-file addition');
assert.deepEqual(manifestNew.styles,manifestOld.styles,'Style order must remain unchanged');
console.log(`PASS provenance from actual Codex baseline through 00-08: ${files} file applications, ${edits} exact edits, ${simulated.size} distinct modules`);
console.log('PASS no unreviewed source-span drift in declared modules or assembly order');
