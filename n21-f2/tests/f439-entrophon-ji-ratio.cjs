'use strict';
const fs=require('node:fs');const vm=require('node:vm');const assert=require('node:assert/strict');const path=require('node:path');
const s=fs.readFileSync(path.join(__dirname,'../src/runtime/instrument/10_entrophon_and_voice_control.js'),'utf8');
const r=s.match(/const Gie=(.*?),aG=/s);assert.ok(r,'ratio and tuning source');
const f=s.slice(s.indexOf('function Yie('),s.indexOf('const Jie=',s.indexOf('function Yie(')));
assert.ok(f.includes('o==="ji-nearest"'),'opt-in ratio mode');
assert.ok(s.includes('id:"ji-nearest",label:"JI · Nearest Ratio (12-tone pool)"'),'UI mode available');
const context={Ew:()=>({enabled:true,rootFreq:220,tuningId:'ji',tuningStrength:1}),Wn:(x,min,max)=>Math.max(min,Math.min(max,x)),qie:x=>x,Xie:(surface,strength)=>strength,fI:(old,desired,strength)=>old+(desired-old)*strength};
vm.createContext(context);vm.runInContext('const Gie='+r[1]+';'+f+'this.tune=Yie',context);
const tune=({cents,mode,root=220,strength=1})=>context.tune({freq:root*Math.pow(2,cents/1200),rootFreq:root,tuningId:mode,strength});
const close=(a,b,tol=1e-7)=>assert.ok(Math.abs(a-b)<tol,`${a} != ${b}`);
close(tune({cents:150,mode:'ji'}),220*9/8);
close(tune({cents:150,mode:'ji-nearest'}),220*16/15);
close(tune({cents:0,mode:'ji-nearest'}),220);
close(tune({cents:1190,mode:'ji-nearest'}),440);
close(tune({cents:-1190,mode:'ji-nearest'}),110);
close(tune({cents:150,mode:'ji-nearest',strength:0}),220*2**(150/1200));
close(tune({cents:150,mode:'31edo'}),220*2**(Math.round(150/1200*31)/31));
console.log('PASS F4.3.9 legacy 12-region JI unchanged, new nearest-ratio opt-in, octave crossings, strength and 31-EDO intact');
