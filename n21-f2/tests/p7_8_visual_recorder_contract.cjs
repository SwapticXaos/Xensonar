'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=process.argv[2]||path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const visual=read('src/rhythm/03_live_drum_bodies.js');
const rec=read('src/audio/03_recorder.js');
const callbacks=read('src/audio/03_rfl_transport_legacy.js');
const header=read('src/runtime/instrument/05_timing_and_admission.js');
const shell=read('src/app/forge/01_room_shell.js');
assert.match(visual,/const Y=\.18\+\.22\*L;t\.strokeStyle=`rgba\(165, 255, 190, \$\{Y\}\)`/,'leaving step is never drawn darker than base');
assert.match(visual,/rgba\(6, 8, 12, 0\.98\)/,'ball is black');
assert.match(header,/onDiscardRecordingFromHeader/,'cancel callback exposed');
assert.match(header,/requestFullscreen/,'fullscreen toggle is functional');
assert.match(header,/Discard recording/,'cancel accessible explanation');
assert.match(shell,/onDiscardRecordingFromHeader/,'cancel wired from actual recorder state');
assert.match(rec,/discardRecording=\(\)=>/,'actual recorder cancel exposed');
assert.match(rec,/onstop=null/,'cancel prevents normal stop processing');
assert.match(callbacks,/isDiscarded/,'decode of cancelled recording prevented');
console.log('PASS P7.8 visual, independent cancel and fullscreen wiring');
