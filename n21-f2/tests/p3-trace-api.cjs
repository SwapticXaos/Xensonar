'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const probe=new Function(fs.readFileSync('src/instruments/00_diagnostics.js','utf8')+';return __XenAudioProbe;')();
assert.equal(typeof probe.begin,'function','P3A needs one stable event ID from the ingress');
assert.equal(probe.begin('particle',1),null,'disabled trace creates no event');
probe.start();const first=probe.begin('particle',1);
assert.equal(typeof first,'string');
probe.record('gate32','particle','admitted',1,first);
probe.record('worklet','particle','accepted',1.008,first,{voiceId:'voice-1'});
let report=probe.read();assert.equal(report.records.length,3);assert(report.records.every(r=>r.eventId===first));
assert.equal(report.records[0].stage,'ingress');assert.equal(report.records[2].details.voiceId,'voice-1');
probe.stop();probe.record('worklet','particle','ended',2,first);assert.equal(probe.read().records.length,3);
probe.start();const second=probe.begin('wave',2);assert.notEqual(first,second,'session restart never aliases old events');
probe.record('worklet','particle','ended',3,first);
assert.equal(probe.read().records.length,1,'old-session completions must not pollute the new capture');
for(let i=0;i<4100;i++)probe.record('gate32','wave','admitted',2,second);
report=probe.stop();assert.equal(report.records.length,4096);assert.equal(report.truncated,5);
assert.equal(report.records[0].seq,6);assert.equal(report.records.at(-1).seq,4101);
assert.equal(report.counts['gate32|wave|admitted'],4100);
console.log('PASS correlated trace IDs, session isolation, disabled capture and bounded chronological ring');
