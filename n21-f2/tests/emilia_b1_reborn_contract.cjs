'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {harness,distance,rms}=require('./emilia3_harness.cjs');
const {api,context,model}=harness();
const source=fs.readFileSync(path.join(__dirname,'../src/forge/emilia/02_lab_ui.js'),'utf8');
const network=fs.readFileSync(path.join(__dirname,'../src/forge/emilia/03_network_color.js'),'utf8');
(async()=>{
  assert.equal(api.MAX_NODES,7,'Cannot allow more nodes than preview permits');
  let recipe=api.snapshot();for(let i=recipe.model.nodes.length;i<7;i++)recipe=api.createNode(recipe,'drive');
  assert.equal(recipe.model.nodes.length,7);
  assert.equal(api.createNode(recipe,'fold').model.nodes.length,7);
  assert.match(source,/emilia-b-field/,'B1 square is reference');
  assert.match(source,/emilia-b-node-list/,'B1 row actions are retained');
  assert.match(source,/Remove node/,'each node must have one-click remove');
  assert.match(source,/value:''/,'role addition resets after each one-click selection');
  assert.match(source,/data-emilia-held-preview/,'B1 large hold button');
  assert.match(source,/drag-ghost/,'B1 keeps original graph while dragging');
  assert.match(network,/function compileEmiliaNetworkColor/);
  const base=api.snapshot(),tone=[{at:t=>({hz:220,gain:t<.7?.55:0})}];
  const run=instrument=>api.renderPCM({instrument,tracks:tone,durationSec:.85,sampleRate:16000});
  const one=await run(base),again=await run(base);
  assert.equal(distance(one.left,again.left),0);
  const moved=api.moveNode(base,base.model.nodes[0].id,.92,.2);
  const two=await run(moved);assert(distance(one.left,two.left)>.07,'different constellations must sound different');
  const top=await run(api.moveNode(base,base.model.nodes[1].id,.57,.12));
  assert(distance(one.left,top.left)>.07,'absolute position must be meaningful');
  const changed=api.editNode(base,base.model.nodes[1].id,{ratio:2.6});
  assert(distance(one.left,(await run(changed)).left)>.07,'node pitch relation must be meaningful');
  assert(rms(one.left)>.003);
  console.log('PASS B1 layout, cap 7, one-click roles, graph shadow and nontrivial network-color audio');
})().catch(e=>{console.error(e.stack);process.exitCode=1});
