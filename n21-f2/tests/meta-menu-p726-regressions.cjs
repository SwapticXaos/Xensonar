'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const meta=fs.readFileSync('src/mix/03_meta_menu.js','utf8');
const quickText=fs.readFileSync('src/mix/03_quick_menu.js','utf8');
function cut(src,start,end){let a=src.indexOf(start),b=src.indexOf(end,a);assert(a>=0&&b>a,`${start} / ${end}`);return src.slice(a,b)}
const intro=cut(quickText,'const __XenSongKinds=','/* P4C2 UI:');
const frag=cut(meta,'const __XenMetaLabels=','const __XenMetaSessions=');
let memory=new Map(),fail=false;
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>{if(fail)throw Error('quota');memory.set(k,v)}};
const existing=[{kind:'grid',id:'17edo',name:'17 EDO'}];
let live=[...existing];
const ctx=vm.createContext({console,crypto:require('node:crypto').webcrypto});
vm.runInContext(intro+'\n'+frag+'\nthis.make=__createXenMetaSessionStore',ctx);
const fromHost=a=>JSON.parse(JSON.stringify(a));
const toVm=a=>vm.runInContext(`JSON.parse(${JSON.stringify(JSON.stringify(a))})`,ctx);
const quick={getItems:()=>toVm(live),replaceItems:v=>(live=fromHost(v))};
const m=ctx.make(storage,quick),other=toVm({kind:'drum',id:'5bars',name:'Five Bars'});
// User input must permit an EMPTY draft: validation belongs to Save, not to Backspace.
assert.equal(m.setName(''),true,'last character must be erasable');
assert.equal(m.snapshot().name,'','input must stay blank while editing');
assert.equal(m.save(),false,'blank session name cannot be saved');
assert.equal(m.snapshot().name,'','failed save cannot force a default name');
assert.equal(m.setName('Session Alpha'),true);
assert.equal(m.save(),true);
const id=m.snapshot().loadedId;
assert.equal(m.addItem(other),true);
assert.equal(m.snapshot().canUndo,true,'adding creates undo');
assert.equal(m.removeItem(other),true);
assert.equal(m.snapshot().items.some(e=>e.id===other.id),false);
assert.equal(m.undo(),true,'right-click removal is reversible');
assert.equal(m.snapshot().items.some(e=>e.id===other.id),true);
assert.equal(m.redo(),true,'redo repeats removal');
assert.equal(m.snapshot().items.some(e=>e.id===other.id),false);
assert.equal(m.undo(),true);
assert.equal(m.setItemColor(other,'border','#ffcc77'),true);
assert.equal(m.undo(),true,'undo color preserves item');
assert.equal(m.itemColor(other).border,undefined);
assert.equal(m.redo(),true,'redo color restores tint');
assert.equal(m.itemColor(other).border,'#ffcc77');
assert.equal(m.undo(),true); // can redo color
assert.equal(m.removeItem(other),true);
assert.equal(m.snapshot().canRedo,false,'new edit clears redo branch');
fail=true;
assert.equal(m.undo(),false,'failing storage cannot consume undo stack');
assert.equal(m.snapshot().items.some(e=>e.id===other.id),false);
assert.equal(m.snapshot().canUndo,true);
fail=false;
assert.equal(m.undo(),true);
assert.equal(m.snapshot().items.some(e=>e.id===other.id),true);
assert.equal(m.load(id),true);
assert.equal(m.snapshot().canUndo,false,'loading saved session resets editing history');
assert.equal(m.snapshot().canRedo,false);
assert.equal(m.newSession(),true);
assert.equal(m.snapshot().canUndo,false);
assert.equal(m.setName(''),true);
const restored=ctx.make(storage,quick);
assert.equal(restored.snapshot().name,'','blank draft survives reload');
console.log('PASS P7.26 session name, undo/redo, color history, save failure, session boundaries');
// Quick selection tracks real adapter changes, not transient short-lived pulse.
const qfrag=cut(quickText,'const __XenQuick=','function __useQuickAdapter(');
const qctx=vm.createContext({localStorage:{getItem:()=>null,setItem:()=>{}},console,setTimeout,clearTimeout});
vm.runInContext(intro+'\n'+qfrag+'\nthis.quick=__XenQuick',qctx);
const q=qctx.quick;
let chosen=null;
const adapter={entries:toVm([{kind:'drum',id:'kick',name:'Kick'}]),selected:'kick',choose:id=>{chosen=id}};
