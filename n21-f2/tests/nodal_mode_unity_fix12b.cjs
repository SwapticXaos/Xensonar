'use strict';
const assert = require('node:assert/strict');
const fs=require('node:fs'), path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const designer=read('src/nodal/07_sound_designer.js');
const legacy=read('src/runtime/instrument/08_library_and_tuning_editor.js');
const css=read('styles/20_nodal_sound_designer.css');
assert.match(designer,/function NodalRoomHeader\(/,'One reusable Room III header must exist');
assert.match(designer,/function koe\(props\)[\s\S]*?className: 'nd-room nd-room-shell'/,'All Room III modes must share the same visible room shell');
assert.match(designer,/data-nodal-designer/,'Existing designer selector must survive');
for(const mode of ['sounddesign','installation','enhancer']) assert(designer.includes("['"+mode+"'"),'Shared header must link '+mode);
assert.match(designer,/aria-pressed[^\n]*mode === id/,'Active mode must be indicated to assistive technology');
assert.match(designer,/className: 'nd-legacy-body/,'Legacy modes must be placed inside the shared shell');
assert.match(legacy,/nd-legacy-meta/,'Installation and Enhancer should carry unified legacy layout hooks');
assert.match(legacy,/nd-legacy-tab-duplicates/,'Old, duplicate mode chooser must be identified to hide');
assert.match(css,/\.nd-legacy-tab-duplicates\s*\{\s*display:\s*none/,'There must be only one visible mode switcher');
assert.match(css,/\.nd-legacy-card\s*\{[^}]*background:\s*transparent/,'Old black panel must use the shared turquoise container');
assert.match(css,/\.nd-legacy-body[^\n]*\.nd-legacy-stage/,'Existing installation canvas must receive the shared stage treatment');
assert(!designer.includes('Raum wird Stimme'), 'No pseudo-poetic German slogans');
assert(!legacy.includes('Start by listening here: root below'), 'Remove prose that does not explain a control');
console.log('PASS unified three-mode Nodal Room III shell, English nav, no duplicate controls, no extra rows');
