const fs=require('fs'),vm=require('vm'),assert=require('assert');
const s=fs.readFileSync(__dirname+'/derived_bass_grid.js','utf8').split('function __XenBassGridRuntime(')[0];
const saved=new Map();const localStorage={getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,String(v))};
const window={}; const context={window,localStorage,Math,Float64Array,Set,Map,Number,Object,JSON,Array};
context.Kp=id=>id==='17edo'?Array.from({length:17},(_,i)=>i*1200/17):Array.from({length:12},(_,i)=>i*100);
context.vF=()=>1200;
context.Au=(mode,tuning)=>context.Kp(tuning).map((_,i)=>mode!=='ionian'||[0,2,4,5,7,9,11].includes(i));
vm.runInNewContext(s+'\nglobalThis.bassGrid=__XenBassGrid;',context);
const g=context.bassGrid;
const params={gridTuning:'12edo',gridBase:55,manualGridMutedSteps:[],manualGridStepOffsets:[]};
assert.equal(g.quantize(61.23),61.23,'unlinked mode is identical to legacy bass');
g.set('12edo',{enabled:true,mutedDegrees:[1,2,3,4,5,6,8,9,11],offsetsCents:{7:-23}});
g.setSource('bass');g.prepare(params);
assert.equal(g.quantize(58),55,'nearest allowed tone maps to root');
const slightlyFlatFifth=55*Math.pow(2,(700-23)/1200);
assert(Math.abs(g.quantize(82)-slightlyFlatFifth)<1e-9,'fifth offset is applied in cents');
assert(Math.abs(g.quantize(97)-55*Math.pow(2,1000/1200))<1e-9,'allowed 10th step is resolved');
assert.equal(g.read('12edo').mutedDegrees.length,9,'sparse: 9 mutes only');
assert.deepEqual(Object.keys(g.exportAll()),['12edo']);
assert(JSON.parse(saved.values().next().value).grids['12edo'].offsetsCents['7']===-23);
g.prepare({...params,gridMode:'ionian'});assert(Math.abs(g.quantize(96)-55*Math.pow(2,(700-23)/1200))>1,'ionian mode excludes muted minor-seventh degree');
g.setSource('main');g.prepare(params);assert.equal(g.quantize(82),82,'main path unaffected');
g.setSource('bass');g.set('12edo',{mutedDegrees:Array.from({length:12},(_,i)=>i)});g.prepare(params);assert(Number.isNaN(g.quantize(82)),'all-muted prevents Bass attack rather than playing unfiltered legacy pitch');
g.importExtensions({'custom:old':{enabled:true,mutedDegrees:[2],offsetsCents:{5:18}}},{'custom:old':'custom:new'},'merge');
assert(g.read('custom:new').enabled&&g.read('custom:new').offsetsCents[5]===18,'archive remaps imported custom tuning IDs');
g.set('17edo',{enabled:true,mutedDegrees:[1,3,5]});g.prepare({...params,gridTuning:'17edo'});assert(Number.isFinite(g.quantize(70)),'17edo table compiles');
console.log('DERIVED BASS GRID: 12 checks passed (sparse, pitch, main bypass, muting, archive, 17edo)');
